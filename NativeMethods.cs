    /// <summary>
    /// Enables or disables click-through behavior using WS_EX_TRANSPARENT.
    /// When enabled, mouse clicks pass directly through the window to background applications.
    /// </summary>
    public static void SetClickThrough(IntPtr hWnd, bool clickThrough)
    {
        nint currentVal = GetWindowLongPtr(hWnd, GWL_EXSTYLE);

        if (clickThrough)
        {
            currentVal |= (nint)(WS_EX_TRANSPARENT | WS_EX_LAYERED);
        }
        else
        {
            currentVal &= ~(nint)WS_EX_TRANSPARENT;
        }

        SetWindowLongPtr(hWnd, GWL_EXSTYLE, currentVal);
    }
}
